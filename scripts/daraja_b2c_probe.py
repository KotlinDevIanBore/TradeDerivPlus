#!/usr/bin/env python3
"""Observe how Daraja's B2C v3 endpoint behaves, against sandbox.

A one-off instrument, like scripts/daraja_probe.py: not part of any suite, not
run by CI, and pointed at sandbox only.

It answers the one question production traffic next door cannot, because that
system never sends the same request twice:

    Does Safaricom actually deduplicate a repeated OriginatorConversationID?

Daraja's own documentation describes that field as "unique string generated by
the merchant system for every B2C request to avoid double disbursement". If the
claim holds, a resend after an ambiguous send is safe and the withdrawal design
can recover from a crash between sending and recording. If it does not hold, the
same resend pays a customer twice, our own guards are the only thing standing
between a crash and a double payout, and the design must never resend — only ask
via Transaction Status. That is a materially different implementation, so it is
established by observation rather than by reading.

It also records, for the fixtures the client's tests are built on:

  * the synchronous acceptance shape,
  * what a rejection looks like (by sending one deliberately),
  * whether the sandbox accepts v3 at all, and what v1 does by comparison,
  * whether a status query by OriginalConversationID works, and its ack shape.

    export MPESA_CONSUMER_KEY=... MPESA_CONSUMER_SECRET=...
    export MPESA_INITIATOR_NAME=testapi
    export MPESA_SECURITY_CREDENTIAL="$(MPESA_INITIATOR_PASSWORD=... go run ./cmd/gencred -cert sandbox.cer)"
    python3 scripts/daraja_b2c_probe.py

Credentials come from the environment only, are never printed, and nothing is
written to disk. The raw bodies below are what belongs in the findings — read
them before sharing.

WHAT IT CANNOT SEE: B2C results arrive asynchronously on a callback URL, and this
script is not a server. So it reports what Daraja says synchronously and leaves
the Result payloads to be collected from whatever is listening at RESULT_URL.
Point that at a request-capture service you control and paste the bodies in.

SAFETY: refuses to run against anything but sandbox. This moves sandbox money
from a sandbox shortcode; against production credentials it would be a real
payout to a real person, and B2C payouts cannot be reversed by any API.
"""
import json
import os
import sys
import time
import urllib.error
import urllib.request
import uuid

BASE = os.environ.get("MPESA_BASE_URL", "https://sandbox.safaricom.co.ke").rstrip("/")
KEY = os.environ.get("MPESA_CONSUMER_KEY", "")
SECRET = os.environ.get("MPESA_CONSUMER_SECRET", "")
SHORTCODE = os.environ.get("MPESA_SHORTCODE", "174379")
INITIATOR = os.environ.get("MPESA_INITIATOR_NAME", "testapi")
CREDENTIAL = os.environ.get("MPESA_SECURITY_CREDENTIAL", "")
# Safaricom's sandbox test number, the same one the STK probe uses.
MSISDN = os.environ.get("PROBE_MSISDN", "254708374149")
AMOUNT = int(os.environ.get("PROBE_AMOUNT", "10"))
# Two DIFFERENT URLs, on purpose: collapsing them is the mistake the client
# refuses to be configured into, and the probe should not model it either.
RESULT_URL = os.environ.get("PROBE_RESULT_URL", "https://example.com/unused/result")
TIMEOUT_URL = os.environ.get("PROBE_TIMEOUT_URL", "https://example.com/unused/timeout")

if "sandbox.safaricom.co.ke" not in BASE:
    sys.exit(
        f"refusing to run against {BASE!r}.\n"
        "This sends a real B2C payout, and B2C payouts cannot be reversed by API. "
        "Sandbox only — set MPESA_BASE_URL to https://sandbox.safaricom.co.ke."
    )
if not (KEY and SECRET):
    sys.exit("set MPESA_CONSUMER_KEY and MPESA_CONSUMER_SECRET in the environment")
if not CREDENTIAL:
    sys.exit(
        "set MPESA_SECURITY_CREDENTIAL — generate it with:\n"
        "  MPESA_INITIATOR_PASSWORD=... go run ./cmd/gencred -cert <sandbox .cer>\n"
        "Use the SANDBOX certificate; the production one yields a credential "
        "sandbox rejects as result code 2001."
    )
if RESULT_URL == TIMEOUT_URL:
    sys.exit("PROBE_RESULT_URL and PROBE_TIMEOUT_URL must differ — see the client's ValidateB2CConfig")


def token():
    req = urllib.request.Request(f"{BASE}/oauth/v1/generate?grant_type=client_credentials")
    import base64 as _b64
    req.add_header("Authorization", "Basic " + _b64.b64encode(f"{KEY}:{SECRET}".encode()).decode())
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)["access_token"]


def post(path, tok, payload):
    """Returns (status, raw_body). Raw, because the shape is what is under test."""
    req = urllib.request.Request(f"{BASE}{path}", data=json.dumps(payload).encode(), method="POST")
    req.add_header("Authorization", f"Bearer {tok}")
    req.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            return r.status, r.read().decode()
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode()
    except Exception as e:  # noqa: BLE001 - a transport failure is an observation
        return 0, f"<transport failure: {e}>"


def b2c_payload(originator, amount=None):
    return {
        "OriginatorConversationID": originator,
        "InitiatorName": INITIATOR,
        "SecurityCredential": CREDENTIAL,
        "CommandID": "BusinessPayment",
        "Amount": AMOUNT if amount is None else amount,
        "PartyA": SHORTCODE,
        "PartyB": MSISDN,
        "Remarks": "TradeDerivPlus B2C probe",
        "QueueTimeOutURL": TIMEOUT_URL,
        "ResultURL": RESULT_URL,
    }


def show(label, status, body):
    print(f"\n--- {label}")
    print(f"HTTP {status}")
    print(body.strip()[:1200])


def main():
    print(f"B2C probe against {BASE} as shortcode {SHORTCODE}, initiator {INITIATOR}")
    print(f"paying {MSISDN} KES {AMOUNT}; results would arrive at {RESULT_URL}")
    print("(the security credential is never printed)")

    tok = token()
    print("\nauthenticated")

    # 1. Does v3 work at all, and what does acceptance look like?
    originator = f"probe-{uuid.uuid4()}"
    status, body = post("/mpesa/b2c/v3/paymentrequest", tok, b2c_payload(originator))
    show(f"v3 accept, OriginatorConversationID={originator}", status, body)
    v3_ok = status == 200 and '"errorCode"' not in body

    # 2. THE QUESTION. The same id again, everything else identical.
    #
    # Read the answer carefully. An error naming a duplicate is the good case:
    # Safaricom is deduplicating and a resend after an ambiguous send is safe.
    # A second clean acceptance is the bad case — it means either two payouts or
    # a silent no-op, and only the Result callbacks can say which. If you see
    # two acceptances, DO NOT conclude it is safe: check whether the test number
    # received one payment or two before trusting any resend.
    if v3_ok:
        time.sleep(5)
        status2, body2 = post("/mpesa/b2c/v3/paymentrequest", tok, b2c_payload(originator))
        show("v3 REPEAT of the same OriginatorConversationID", status2, body2)
        print("\n    >>> If this was refused as a duplicate: a resend after an ambiguous")
        print("        send is safe, and the withdrawal design may resend.")
        print("    >>> If this was accepted again: the id does NOT deduplicate. Check the")
        print("        test number for one payment or two, and treat resending as")
        print("        forbidden — reconcile by Transaction Status only.")

    # 3. A deliberate rejection, to record what one looks like. Amount 0 is
    #    refused by Daraja rather than by us.
    status3, body3 = post("/mpesa/b2c/v3/paymentrequest", tok, b2c_payload(f"probe-{uuid.uuid4()}", amount=0))
    show("v3 deliberate rejection (amount 0)", status3, body3)

    # 4. v1 for comparison, so the report can say what was actually observed
    #    rather than that v1 was assumed absent. Nothing here uses v1.
    status4, body4 = post("/mpesa/b2c/v1/paymentrequest", tok, b2c_payload(f"probe-{uuid.uuid4()}"))
    show("v1 for comparison (not used by this codebase)", status4, body4)

    # 5. Can a payout be asked about by the id we chose, with no receipt?
    status5, body5 = post("/mpesa/transactionstatus/v1/query", tok, {
        "Initiator": INITIATOR,
        "SecurityCredential": CREDENTIAL,
        "CommandID": "TransactionStatusQuery",
        "OriginalConversationID": originator,
        "PartyA": SHORTCODE,
        "IdentifierType": "4",
        "ResultURL": RESULT_URL,
        "QueueTimeOutURL": TIMEOUT_URL,
        "Remarks": "probe status by originator id",
    })
    show("transaction status by OriginalConversationID", status5, body5)

    # 6. Account balance, whose result carries the utility float.
    status6, body6 = post("/mpesa/accountbalance/v1/query", tok, {
        "Initiator": INITIATOR,
        "SecurityCredential": CREDENTIAL,
        "CommandID": "AccountBalance",
        "PartyA": SHORTCODE,
        "IdentifierType": "4",
        "Remarks": "probe balance",
        "ResultURL": RESULT_URL,
        "QueueTimeOutURL": TIMEOUT_URL,
    })
    show("account balance", status6, body6)

    print("\n" + "=" * 60)
    print("Synchronous answers above. The Result payloads — which carry the")
    print("result codes, the receipt and the utility float — arrive at")
    print(f"{RESULT_URL} and {TIMEOUT_URL}; collect them there and paste them into")
    print("the findings. What to update once you have them:")
    print("  * mpesaclient.PayoutFailureCodes, if an observed code is missing")
    print("  * the fixtures in pkg/mpesaclient/b2c_test.go, to observed bodies")
    print("  * the resend decision in the CP2 plan, from step 2 above")


if __name__ == "__main__":
    main()
